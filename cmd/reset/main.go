// Package main представляет собой утилиту для генерации методов Reset() для структур, помеченных комментарием // generate:reset.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"strings"

	"golang.org/x/tools/go/packages"
)

func main() {
	// Конфигурация для загрузки пакетов. Нам нужен синтаксис и информация о типах.
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
	}

	// Загружаем все пакеты, начиная с текущей директории
	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		log.Fatalf("Ошибка загрузки пакетов: %v", err)
	}

	for _, pkg := range pkgs {
		if len(pkg.Errors) > 0 {
			// Игнорируем пакеты с ошибками компиляции (например, testdata)
			continue
		}
		if len(pkg.GoFiles) == 0 {
			continue
		}

		var generatedMethods []string

		// Проходим по всем файлам пакета
		for _, file := range pkg.Syntax {
			for _, decl := range file.Decls {
				genDecl, ok := decl.(*ast.GenDecl)
				if !ok || genDecl.Tok != token.TYPE {
					continue
				}

				// Проверяем наличие комментария // generate:reset
				hasTag := false
				if genDecl.Doc != nil {
					for _, comment := range genDecl.Doc.List {
						if strings.Contains(comment.Text, "generate:reset") {
							hasTag = true
							break
						}
					}
				}
				if !hasTag {
					continue
				}

				// Ищем структуры в этой декларации
				for _, spec := range genDecl.Specs {
					typeSpec, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}
					structType, ok := typeSpec.Type.(*ast.StructType)
					if !ok {
						continue
					}

					structName := typeSpec.Name.Name
					methodCode := generateResetMethod(structName, structType, pkg)
					if methodCode != "" {
						generatedMethods = append(generatedMethods, methodCode)
					}
				}
			}
		}

		// Если для пакета есть что генерировать, создаём файл reset.gen.go
		if len(generatedMethods) > 0 {
			var buf bytes.Buffer
			buf.WriteString("// Code generated by cmd/reset; DO NOT EDIT.\n\n")
			buf.WriteString(fmt.Sprintf("package %s\n\n", pkg.Name))

			for _, method := range generatedMethods {
				buf.WriteString(method)
				buf.WriteString("\n\n")
			}

			// Форматируем код
			formatted, err := format.Source(buf.Bytes())
			if err != nil {
				log.Printf("Ошибка форматирования кода для пакета %s: %v\nСгенерированный код:\n%s", pkg.Name, err, buf.String())
				continue
			}

			// Определяем путь для записи (в той же директории, где лежит первый .go файл пакета)
			dir := filepath.Dir(pkg.GoFiles[0])
			outputPath := filepath.Join(dir, "reset.gen.go")

			if err := os.WriteFile(outputPath, formatted, 0644); err != nil {
				log.Printf("Ошибка записи файла %s: %v", outputPath, err)
			} else {
				fmt.Printf("Сгенерирован: %s\n", outputPath)
			}
		}
	}
}

// generateResetMethod создаёт исходный код метода Reset() для данной структуры.
func generateResetMethod(structName string, structType *ast.StructType, pkg *packages.Package) string {
	var bodyLines []string

	// Проверка на nil для указателя на структуру
	bodyLines = append(bodyLines, fmt.Sprintf("func (rs *%s) Reset() {", structName))
	bodyLines = append(bodyLines, "\tif rs == nil {")
	bodyLines = append(bodyLines, "\t\treturn")
	bodyLines = append(bodyLines, "\t}")
	bodyLines = append(bodyLines, "")

	for _, field := range structType.Fields.List {
		if len(field.Names) == 0 {
			continue
		}

		fieldName := field.Names[0].Name
		fieldType := pkg.TypesInfo.TypeOf(field.Type)

		logic := generateFieldResetLogic(fieldName, fieldType)
		if logic != "" {
			bodyLines = append(bodyLines, logic)
		}
	}

	bodyLines = append(bodyLines, "}")
	return strings.Join(bodyLines, "\n")
}

// generateFieldResetLogic возвращает строку кода для сброса конкретного поля.
func generateFieldResetLogic(fieldName string, t types.Type) string {
	switch typ := t.(type) {
	case *types.Basic:
		zero := getBasicZero(typ.Kind())
		return fmt.Sprintf("\trs.%s = %s", fieldName, zero)

	case *types.Pointer:
		elem := typ.Elem()
		if basic, ok := elem.(*types.Basic); ok {
			zero := getBasicZero(basic.Kind())
			return fmt.Sprintf("\tif rs.%s != nil {\n\t\t*rs.%s = %s\n\t}", fieldName, fieldName, zero)
		}
		// Для указателей на структуры, интерфейсы и именованные типы используем type assertion
		return fmt.Sprintf("\tif rs.%s != nil {\n\t\tif r, ok := any(rs.%s).(interface{ Reset() }); ok {\n\t\t\tr.Reset()\n\t\t}\n\t}", fieldName, fieldName)

	case *types.Slice:
		return fmt.Sprintf("\trs.%s = rs.%s[:0]", fieldName, fieldName)

	case *types.Map:
		return fmt.Sprintf("\tclear(rs.%s)", fieldName)

	case *types.Struct:
		return fmt.Sprintf("\trs.%s.Reset()", fieldName)

	case *types.Named, *types.Interface:
		// Для именованных типов и интерфейсов проверяем наличие метода Reset()
		return fmt.Sprintf("\tif r, ok := any(rs.%s).(interface{ Reset() }); ok {\n\t\tr.Reset()\n\t}", fieldName)
	}
	return ""
}

// getBasicZero возвращает строковое представление нулевого значения для примитивного типа.
func getBasicZero(kind types.BasicKind) string {
	switch kind {
	case types.Int, types.Int8, types.Int16, types.Int32, types.Int64,
		types.Uint, types.Uint8, types.Uint16, types.Uint32, types.Uint64, types.Uintptr,
		types.Float32, types.Float64, types.Complex64, types.Complex128:
		return "0"
	case types.String:
		return `""`
	case types.Bool:
		return "false"
	default:
		return "nil"
	}
}