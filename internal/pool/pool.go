// Package pool предоставляет универсальный типобезопасный пул объектов с автоматическим сбросом состояния перед возвратом в пул.
package pool

import (
	"sync"
)

// Resettable описывает интерфейс для типов, которые могут быть сброшены к начальному состоянию. Используется как ограничение для дженерик-параметра Pool.
type Resettable interface {
	Reset()
}

// Pool представляет собой типобезопасную обёртку над sync.Pool.
// Параметр типа T ограничен интерфейсом Resettable, что гарантирует
// наличие метода Reset() у всех объектов, хранящихся в пуле.
//
// Перед возвратом объекта в пул (метод Put) автоматически вызывается
// метод Reset(), что предотвращает утечку состояния между использованиями.
type Pool[T Resettable] struct {
	pool sync.Pool
}

// New создаёт и возвращает новый экземпляр Pool для типа T.
// Параметр newFunc — это функция-конструктор, которая вызывается,
// когда в пуле нет свободных объектов (стандартное поведение sync.Pool).
func New[T Resettable](newFunc func() T) *Pool[T] {
	return &Pool[T]{
		pool: sync.Pool{
			New: func() any {
				return newFunc()
			},
		},
	}
}

// Get возвращает объект из пула.
// Если пул пуст, вызывается функция-конструктор, переданная в New().
// Возвращаемый объект гарантированно имеет тип T.
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put сбрасывает состояние объекта (вызывая Reset()) и возвращает его в пул.
// Это гарантирует, что следующий вызов Get() вернёт "чистый" объект.
func (p *Pool[T]) Put(obj T) {
	obj.Reset() // Сбрасываем состояние перед возвратом в пул
	p.pool.Put(obj)
}